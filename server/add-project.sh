#!/usr/bin/env bash
# Add an isolated MiniCollection project (console + its devices) on this host.
#
#   sudo ./add-project.sh <project-name> <public-port> [internal-port] [public-base-url]
#
# Example:
#   sudo ./add-project.sh project_lgy 9002
#   sudo ./add-project.sh project_lgy 9002 10002 http://203.0.113.10:9002
#
# Each project gets:
#   - its own systemd service and data root (separate SQLite database);
#   - its own upload/download tokens (the upload token identifies devices,
#     the download token identifies the console);
#   - its own Nginx site, so a console/device pointed at another project's
#     port or token can never read or control this project's devices.
#
# Re-running the command is safe: tokens and data are kept, code/service/nginx
# are refreshed.
set -euo pipefail

if [[ ${EUID} -ne 0 ]]; then
  echo "Run this installer with sudo." >&2
  exit 1
fi

if [[ $# -lt 2 || $# -gt 4 ]]; then
  echo "Usage: sudo $0 <project-name> <public-port> [internal-port] [public-base-url]" >&2
  exit 1
fi

PROJECT=$1
PUBLIC_PORT=$2
SOURCE_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
CODE_DIR=${MSEED_CODE_DIR:-$SOURCE_DIR}

if [[ ! "$PROJECT" =~ ^[a-z0-9][a-z0-9_-]*$ ]]; then
  echo "Invalid project name: $PROJECT (use lowercase letters, digits, '-' or '_')" >&2
  exit 1
fi
if ! [[ "$PUBLIC_PORT" =~ ^[0-9]+$ ]] || (( 10#$PUBLIC_PORT < 1024 || 10#$PUBLIC_PORT > 65535 )); then
  echo "Invalid public port: $PUBLIC_PORT" >&2
  exit 1
fi
PUBLIC_PORT=$((10#$PUBLIC_PORT))
INTERNAL_PORT=${3:-$((PUBLIC_PORT + 1000))}
if ! [[ "$INTERNAL_PORT" =~ ^[0-9]+$ ]] || (( 10#$INTERNAL_PORT < 1024 || 10#$INTERNAL_PORT > 65535 )); then
  echo "Invalid internal port: $INTERNAL_PORT" >&2
  exit 1
fi
INTERNAL_PORT=$((10#$INTERNAL_PORT))
if (( PUBLIC_PORT == INTERNAL_PORT )); then
  echo "public-port and internal-port must differ." >&2
  exit 1
fi

# Alibaba Cloud ECS returns the private VPC address from `hostname -I`.
# Prefer the EIP/public metadata address so printed client configs are usable.
detect_public_ip() {
  local ip=""
  ip=$(curl -fsS --max-time 2 http://100.100.100.200/latest/meta-data/eipv4 2>/dev/null || true)
  if [[ -z "$ip" ]]; then
    ip=$(curl -fsS --max-time 2 http://100.100.100.200/latest/meta-data/public-ipv4 2>/dev/null || true)
  fi
  if [[ -z "$ip" ]]; then
    ip=$(hostname -I | awk '{print $1}')
  fi
  printf '%s' "$ip"
}

BASE_VENV=/opt/mseed-server/venv
APP_DIR=/opt/mseed-server-projects/$PROJECT
DATA_PARENT=/var/lib/mseed-server-projects
DATA_DIR=$DATA_PARENT/$PROJECT
ENV_FILE=/etc/mseed-server-$PROJECT.env
SERVICE_NAME=mseed-server-$PROJECT
SERVICE_FILE=/etc/systemd/system/$SERVICE_NAME.service
NGINX_SITE=/etc/nginx/sites-available/$SERVICE_NAME

for required in mseed_server.py; do
  if [[ ! -f "$CODE_DIR/$required" ]]; then
    echo "Missing $CODE_DIR/$required (set MSEED_CODE_DIR to the server source directory)." >&2
    exit 1
  fi
done
if [[ ! -x "$BASE_VENV/bin/uvicorn" ]]; then
  echo "Base installation is missing: run install-ubuntu-22.04.sh first." >&2
  exit 1
fi
if ! id mseed >/dev/null 2>&1; then
  useradd --system --home-dir "$DATA_PARENT" --shell /usr/sbin/nologin mseed
fi

install -d -o root -g root -m 755 "$APP_DIR"
install -d -o mseed -g mseed -m 750 "$DATA_PARENT"
install -d -o mseed -g mseed -m 750 "$DATA_DIR"
install -o root -g root -m 644 "$CODE_DIR/mseed_server.py" "$APP_DIR/mseed_server.py"

if [[ ! -f "$ENV_FILE" ]]; then
  upload_token=$(openssl rand -hex 32)
  download_token=$(openssl rand -hex 32)
  public_base_url=${4:-}
  cat >"$ENV_FILE" <<EOF
MSEED_PROJECT_NAME=$PROJECT
MSEED_DATA_ROOT=$DATA_DIR
MSEED_UPLOAD_TOKEN=$upload_token
MSEED_DOWNLOAD_TOKEN=$download_token
# Optional: dedicated control-plane token for custom clients. The console
# always uses the download token, so this is normally left unset.
#MSEED_PROJECT_TOKEN=
EOF
  if [[ -n "$public_base_url" ]]; then
    echo "MSEED_PUBLIC_BASE_URL=${public_base_url%/}" >>"$ENV_FILE"
  fi
  chmod 600 "$ENV_FILE"
fi

cat >"$SERVICE_FILE" <<EOF
[Unit]
Description=MiniCollection mseed API - $PROJECT
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=mseed
Group=mseed
WorkingDirectory=$APP_DIR
EnvironmentFile=$ENV_FILE
ExecStart=$BASE_VENV/bin/uvicorn mseed_server:app --host 127.0.0.1 --port $INTERNAL_PORT --workers 1
Restart=always
RestartSec=3
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF

cat >"$NGINX_SITE" <<EOF
# Generated by add-project.sh for project "$PROJECT".
server {
    listen $PUBLIC_PORT;
    server_name _;

    client_max_body_size 2m;

    location / {
        proxy_pass http://127.0.0.1:$INTERNAL_PORT;
        proxy_http_version 1.1;
        proxy_set_header Host \$http_host;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_request_buffering off;
        proxy_read_timeout 60s;
    }
}
EOF

ln -sfn "$NGINX_SITE" /etc/nginx/sites-enabled/$SERVICE_NAME
nginx -t
systemctl daemon-reload
systemctl enable --now "$SERVICE_NAME.service"
systemctl restart "$SERVICE_NAME.service"
systemctl reload nginx.service

for attempt in {1..20}; do
  if curl --fail --silent "http://127.0.0.1:$INTERNAL_PORT/healthz" >/dev/null; then
    break
  fi
  if [[ $attempt -eq 20 ]]; then
    echo "Health check failed. Inspect: journalctl -u $SERVICE_NAME.service" >&2
    exit 1
  fi
  sleep 1
done

if command -v ufw >/dev/null 2>&1 && ufw status | grep -q '^Status: active'; then
  ufw allow "$PUBLIC_PORT"/tcp
fi

upload_token=$(grep -E '^MSEED_UPLOAD_TOKEN=' "$ENV_FILE" | cut -d= -f2-)
download_token=$(grep -E '^MSEED_DOWNLOAD_TOKEN=' "$ENV_FILE" | cut -d= -f2-)
server_ip=$(detect_public_ip)
public_base_url=$(grep -E '^MSEED_PUBLIC_BASE_URL=' "$ENV_FILE" | cut -d= -f2- || true)
public_base_url=${public_base_url:-http://${server_ip}:${PUBLIC_PORT}}

echo
echo "Project $PROJECT is ready."
echo "  Public URL:      $public_base_url"
echo "  Internal port:   127.0.0.1:$INTERNAL_PORT"
echo "  Data root:       $DATA_DIR (per-project database)"
echo "  Service:         systemctl status $SERVICE_NAME.service"
if [[ -z "$(grep -E '^MSEED_PUBLIC_BASE_URL=' "$ENV_FILE" || true)" && \
      "$server_ip" =~ ^(10\.|127\.|172\.(1[6-9]|2[0-9]|3[01])\.|192\.168\.) ]]; then
  echo "  WARNING: detected a private address. Pass the public base URL as the 4th"
  echo "           argument (for example http://公网IP:$PUBLIC_PORT) so download"
  echo "           links are correct."
fi
echo
echo "Device /opt/MiniCollection/data/Config.ini:"
echo "  [Upload]"
echo "  serverUrl=$public_base_url"
echo "  token=$upload_token"
echo
echo "Console config.ini:"
echo "  [Server]"
echo "  url=$public_base_url"
echo "  downloadToken=$download_token"
echo
echo "Credentials file (root only): $ENV_FILE"
